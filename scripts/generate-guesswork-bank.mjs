#!/usr/bin/env node
/**
 * Generates the Guesswork word bank: the daily answers and the accepted guesses, in
 * English (`guesswork@1`) and in Albanian (`gjeje@1`).
 *
 *   node scripts/generate-guesswork-bank.mjs           # print a summary
 *   node scripts/generate-guesswork-bank.mjs --write   # rewrite the bank's two copies
 *
 * --write rewrites `src/lib/games/guesswork-bank.ts` and the four lists inside
 * `supabase/migrations/20261222120000_guesswork_sessions.sql`. The two must always
 * match; `guesswork.test.ts` reads the migration and asserts they do. The answer
 * order is what the days walk, so regenerating with different words changes the
 * daily answers and needs a new rules version.
 *
 * ## Sources
 *
 *   - English answers: every clued five-letter word in scripts/crossword/words.txt.
 *   - English guesses: scripts/guesswork/guesses-en.txt.
 *   - Albanian answers: scripts/guesswork/answers-sq.txt.
 *   - Albanian guesses: scripts/guesswork/guesses-sq.txt.
 *
 * A word in a guess list that is also an answer is kept once, as an answer. Every
 * word must be exactly five squares of its language's alphabet — English A–Z,
 * Albanian A–Z without W, plus Ç and Ë — or the script stops.
 *
 * ## The order
 *
 * The answers are shuffled once, by a fixed-seed LCG, so the days do not walk the
 * alphabet; day `d` is answer `d mod n`. The guesses are sorted.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MIGRATION = "supabase/migrations/20261222120000_guesswork_sessions.sql";

const LANGUAGES = {
  en: { letters: /^[A-Z]{5}$/u, seed: 20261222 },
  sq: { letters: /^[A-VX-ZÇË]{5}$/u, seed: 20261223 },
};

function lines(path) {
  return readFileSync(resolve(ROOT, path), "utf8")
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#"));
}

function check(words, language, source) {
  const bad = words.filter((word) => !LANGUAGES[language].letters.test(word));
  if (bad.length) throw new Error(`${source}: not five ${language} letters: ${bad.join(", ")}`);
  return words;
}

function shuffled(words, seed) {
  let state = seed >>> 0;
  const out = [...words];
  for (let i = out.length - 1; i > 0; i -= 1) {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    const j = state % (i + 1);
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

function build(language, answerWords, guessWords) {
  const answers = [...new Set(answerWords)].sort();
  const taken = new Set(answers);
  const guesses = [...new Set(guessWords)].filter((word) => !taken.has(word)).sort();
  return { answers: shuffled(answers, LANGUAGES[language].seed), guesses };
}

const english = build(
  "en",
  check(
    lines("scripts/crossword/words.txt")
      .map((line) => line.split("|")[0].trim())
      .filter((word) => /^[A-Z]{5}$/.test(word)),
    "en",
    "words.txt",
  ),
  check(lines("scripts/guesswork/guesses-en.txt"), "en", "guesses-en.txt"),
);
const albanian = build(
  "sq",
  check(lines("scripts/guesswork/answers-sq.txt"), "sq", "answers-sq.txt"),
  check(lines("scripts/guesswork/guesses-sq.txt"), "sq", "guesses-sq.txt"),
);

const summary = {
  en: { answers: english.answers.length, guesses: english.guesses.length },
  sq: { answers: albanian.answers.length, guesses: albanian.guesses.length },
};

if (!process.argv.includes("--write")) {
  console.log(JSON.stringify(summary, null, 2));
  process.exit(0);
}

/** Words as wrapped lines of quoted strings, `per` to a line. */
function wrap(words, quote, indent, per = 10) {
  const rows = [];
  for (let i = 0; i < words.length; i += per) {
    rows.push(
      indent +
        words
          .slice(i, i + per)
          .map((word) => `${quote}${word}${quote}`)
          .join(", "),
    );
  }
  return rows.join(",\n");
}

writeFileSync(
  resolve(ROOT, "src/lib/games/guesswork-bank.ts"),
  `/**
 * The Guesswork word bank: daily answers in the order the days walk them, and the
 * other words accepted as guesses, in English (\`guesswork@1\`) and Albanian
 * (\`gjeje@1\`). Generated by \`scripts/generate-guesswork-bank.mjs\`, which explains
 * the sources; the database holds the same lists. Do not edit by hand. Loaded only
 * when a run starts, so the words stay out of the main bundle.
 */
export const GUESSWORK_ANSWERS: readonly string[] = [
${wrap(english.answers, '"', "  ", 1)},
];

export const GUESSWORK_GUESSES: readonly string[] = [
${wrap(english.guesses, '"', "  ", 1)},
];

export const GJEJE_ANSWERS: readonly string[] = [
${wrap(albanian.answers, '"', "  ", 1)},
];

export const GJEJE_GUESSES: readonly string[] = [
${wrap(albanian.guesses, '"', "  ", 1)},
];
`,
);

const migration = resolve(ROOT, MIGRATION);
let sql = readFileSync(migration, "utf8");
for (const [name, words] of [
  ["guesswork-answers", english.answers],
  ["guesswork-guesses", english.guesses],
  ["gjeje-answers", albanian.answers],
  ["gjeje-guesses", albanian.guesses],
]) {
  const begin = sql.indexOf(`    -- ${name}:begin\n`);
  const end = sql.indexOf(`    -- ${name}:end`);
  if (begin < 0 || end < 0) throw new Error(`the migration has no ${name} markers`);
  const head = sql.slice(0, begin) + `    -- ${name}:begin\n`;
  sql = `${head}${wrap(words, "'", "    ")}\n${sql.slice(end)}`;
}
writeFileSync(migration, sql);
console.log(`wrote ${JSON.stringify(summary)}`);
