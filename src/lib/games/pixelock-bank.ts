/**
 * Pixelock's pictures: one 10 × 10 drawing a day, `#` for a filled cell.
 *
 * Day `d` plays picture `d mod n`. The database holds each picture's cells —
 * `public.pixelock_picture` in
 * `supabase/migrations/20270105120100_pixelock_sessions.sql`, written by
 * `bun scripts/generate-daily-banks.ts --write` — and `pixelock.test.ts` fails if
 * the two copies drift, or if a picture cannot be solved line by line.
 *
 * A picture's place in the list is its day: only add at the end (and only under a
 * new rules version, since old runs were played on the old list).
 */

export type PixelockPicture = {
  /** What the picture is, shown once it is drawn. */
  readonly name: string;
  readonly rows: readonly string[];
};

function pic(name: string, ...rows: string[]): PixelockPicture {
  if (rows.length !== 10 || rows.some((row) => !/^[#.]{10}$/.test(row))) {
    throw new Error(`${name} is not a 10 × 10 picture`);
  }
  return { name, rows };
}

