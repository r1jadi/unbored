-- ─────────────────────────────────────────────────────────────────────────────
-- Complete a run: replay, verify, then record
-- ─────────────────────────────────────────────────────────────────────────────

create or replace function public.complete_crossword_run(
  p_session_id  uuid,
  p_actions     integer[],
  p_score       bigint,
  p_duration_ms integer
)
returns public.play_result
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_result   public.play_result;
  v_session  public.game_sessions;
  v_game     public.games;
  v_user     uuid := auth.uid();
  v_grid     text;
  v_side     integer;
  -- The player's letters, 1-based: '' empty, else A–Z; and which are revealed.
  v_letters  text[];
  v_revealed boolean[];
  v_open     integer;
  v_right    integer := 0;
  v_solved   boolean := false;
  v_checks   integer := 0;
  v_reveals  integer := 0;
  v_placed   integer := 0;
  v_action   integer;
  v_cell     integer;
  v_code     integer;
  v_letter   text;
  v_score    bigint := 0;
  v_digest   text;
  v_elapsed  bigint;
  v_best     bigint;
  v_rank     bigint;
begin
  if p_session_id is null then
    raise exception 'a session id is required' using errcode = '22023';
  end if;
  if p_actions is null or array_position(p_actions, null) is not null then
    raise exception 'actions must be a dense array of moves' using errcode = '22023';
  end if;
  if p_duration_ms is null or p_duration_ms < 1 then
    raise exception 'duration must be a positive number of milliseconds' using errcode = '22023';
  end if;
  if p_score is null or p_score < 0 then
    raise exception 'a claimed score is zero or more' using errcode = '22023';
  end if;

  select * into v_session from public.game_sessions s where s.id = p_session_id for update;

  if not found
     or (v_session.user_id is not null and v_session.user_id is distinct from v_user)
     or (v_session.user_id is null and v_user is not null) then
    v_result.outcome := 'not_found';
    v_result.session_id := p_session_id;
    return v_result;
  end if;

  select * into v_game from public.games g where g.id = v_session.game_id;

  -- One ranked completion a day: a completion and a start (or two completions)
  -- meet here in a fixed order, as 7 Second's do.
  if v_session.user_id is not null then
    perform pg_advisory_xact_lock(
      hashtextextended(v_session.game_id::text || ':' || v_session.user_id::text, 0)
    );
  end if;

  v_digest := md5(concat_ws('|',
    v_session.rules_version,
    v_session.seed::text,
    array_to_string(p_actions, ','),
    p_score::text
  ));

  if v_session.completed_at is not null then
    if v_session.verified_digest = v_digest then
      v_result.outcome       := 'duplicate';
      v_result.session_id    := v_session.id;
      v_result.game_slug     := v_game.slug;
      v_result.score         := v_session.verified_score;
      v_result.duration_ms   := p_duration_ms;
      v_result.ranked        := v_session.user_id is not null;
      v_result.recorded_at   := v_session.completed_at;
      if v_session.user_id is not null then
        select max(s.score) into v_best from public.scores s
         where s.game_id = v_session.game_id and s.user_id = v_session.user_id;
        select count(*) + 1 into v_rank from (
          select s.user_id, max(s.score) as best
            from public.scores s
           where s.game_id = v_session.game_id and s.user_id is not null
           group by s.user_id
        ) t where t.best > coalesce(v_best, 0) and t.user_id <> v_session.user_id;
        v_result.personal_best := v_best;
        v_result.board_rank    := v_rank;
      end if;
      return v_result;
    end if;

    v_result.outcome := 'closed';
    v_result.session_id := v_session.id;
    v_result.game_slug := v_game.slug;
    v_result.score := v_session.verified_score;
    return v_result;
  end if;

  if v_session.abandoned_at is not null then
    v_result.outcome := 'abandoned';
    v_result.session_id := v_session.id;
    v_result.game_slug := v_game.slug;
    return v_result;
  end if;

  if now() >= v_session.expires_at then
    v_result.outcome := 'expired';
    v_result.session_id := v_session.id;
    v_result.game_slug := v_game.slug;
    return v_result;
  end if;

  if v_session.rules_version is distinct from public.crossword_rules_version() then
    v_result.outcome := 'wrong_rules';
    v_result.session_id := v_session.id;
    v_result.game_slug := v_game.slug;
    return v_result;
  end if;

  if v_session.user_id is not null and exists (
    select 1
      from public.game_sessions s
     where s.game_id = v_session.game_id
       and s.user_id = v_session.user_id
       and s.seed = v_session.seed
       and s.id <> v_session.id
       and s.completed_at is not null
  ) then
    v_result.outcome := 'already_played';
    v_result.session_id := v_session.id;
    v_result.game_slug := v_game.slug;
    return v_result;
  end if;

  if coalesce(array_length(p_actions, 1), 0) > public.crossword_max_actions() then
    v_result.outcome := 'invalid_actions';
    v_result.session_id := v_session.id;
    v_result.game_slug := v_game.slug;
    return v_result;
  end if;

  v_elapsed := (extract(epoch from (now() - v_session.started_at)) * 1000)::bigint;
  if p_duration_ms > v_elapsed + 2000 then
    v_result.outcome := 'invalid_duration';
    v_result.session_id := v_session.id;
    v_result.game_slug := v_game.slug;
    return v_result;
  end if;

  -- ── The replay ───────────────────────────────────────────────────────────
  -- A move is one of three kinds (mirrored by src/lib/games/crossword.ts):
  --   cell × 32 + code — put a letter (code 1–26, A–Z) in a white cell, or clear
  --                      it (code 0); a revealed cell is locked, and a move that
  --                      changes nothing is not a move;
  --   1600             — check the grid (a penalty; the marks are the client's);
  --   1700 + cell      — reveal a white cell's letter, which locks it.
  -- The run is over once the grid matches the solution; a move after that is
  -- impossible play. A run that stops unsolved is valid and scores nothing.
  v_grid := public.crossword_grid(v_session.seed);
  v_side := round(sqrt(length(v_grid)))::integer;
  v_letters := array_fill(''::text, array[length(v_grid)]);
  v_revealed := array_fill(false, array[length(v_grid)]);
  v_open := length(replace(v_grid, '#', ''));

  foreach v_action in array coalesce(p_actions, array[]::integer[]) loop
    if v_solved or v_action < 0 then
      v_result.outcome := 'invalid_actions';
      v_result.session_id := v_session.id;
      v_result.game_slug := v_game.slug;
      return v_result;
    end if;

    if v_action = 1600 then
      v_checks := v_checks + 1;
    else
      if v_action >= 1700 then
        v_cell := v_action - 1700;
        v_code := -1;
      else
        v_cell := v_action / 32;
        v_code := v_action % 32;
      end if;
      if v_cell >= length(v_grid) or substr(v_grid, v_cell + 1, 1) = '#'
         or v_revealed[v_cell + 1] or v_code > 26 then
        v_result.outcome := 'invalid_actions';
        v_result.session_id := v_session.id;
        v_result.game_slug := v_game.slug;
        return v_result;
      end if;

      if v_code < 0 then
        v_letter := substr(v_grid, v_cell + 1, 1);
        v_revealed[v_cell + 1] := true;
        v_reveals := v_reveals + 1;
      elsif v_code = 0 then
        v_letter := '';
      else
        v_letter := chr(64 + v_code);
      end if;

      if v_code >= 0 and v_letters[v_cell + 1] = v_letter then
        v_result.outcome := 'invalid_actions';
        v_result.session_id := v_session.id;
        v_result.game_slug := v_game.slug;
        return v_result;
      end if;

      -- Keep count of the cells that are right, so solving is one comparison.
      if v_letters[v_cell + 1] = substr(v_grid, v_cell + 1, 1) then
        v_right := v_right - 1;
      end if;
      v_letters[v_cell + 1] := v_letter;
      if v_letter = substr(v_grid, v_cell + 1, 1) then
        v_right := v_right + 1;
      end if;
      v_solved := v_right = v_open;
    end if;

    v_placed := v_placed + 1;
  end loop;

  -- The score is the database's: the solving time is its own, from the session's
  -- start to now, less three seconds for the submission's trip. The client's claim
  -- was its estimate from its own clock; it is kept in the digest, not trusted.
  if v_solved then
    v_score := public.crossword_score(
      v_side,
      (greatest(0, v_elapsed - 3000) / 1000)::integer,
      v_checks,
      v_reveals
    );
  end if;

  update public.game_sessions s
     set completed_at    = now(),
         verified_score  = v_score,
         verified_digest = v_digest
   where s.id = v_session.id
  returning * into v_session;

  if v_session.user_id is not null then
    insert into public.scores (session_id, game_id, user_id, score, duration_ms)
    values (v_session.id, v_session.game_id, v_session.user_id, v_score, p_duration_ms);
  end if;

  v_result.outcome         := 'recorded';
  v_result.session_id      := v_session.id;
  v_result.game_slug       := v_game.slug;
  v_result.score           := v_score;
  v_result.cleared_columns := case when v_solved then 1 else 0 end;
  v_result.tiles_placed    := v_placed;
  v_result.duration_ms     := p_duration_ms;
  v_result.ranked          := v_session.user_id is not null;
  v_result.recorded_at     := v_session.completed_at;

  if v_session.user_id is not null then
    select max(s.score) into v_best from public.scores s
     where s.game_id = v_session.game_id and s.user_id = v_session.user_id;
    select count(*) + 1 into v_rank from (
      select s.user_id, max(s.score) as best
        from public.scores s
       where s.game_id = v_session.game_id and s.user_id is not null
       group by s.user_id
    ) t where t.best > coalesce(v_best, 0) and t.user_id <> v_session.user_id;
    v_result.personal_best := v_best;
    v_result.board_rank    := v_rank;
  end if;

  return v_result;
end;
$$;

