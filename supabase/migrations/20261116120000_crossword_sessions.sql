create or replace function public.crossword_rules_version()
returns text language sql immutable set search_path = '' as $$ select 'crossword@1'::text $$;

create or replace function public.crossword_max_actions()
returns integer language sql immutable set search_path = '' as $$ select 2048 $$;

-- The score of a solve: `p_side` is 5 or 7, `p_seconds` the solving time the
-- verifier measured. The base holds for the grace period (30 s for a mini, 60 s
-- for a midi), then falls four points a second to the floor (a tenth of the base);
-- checks and reveals come off after, and nothing goes below zero.
create or replace function public.crossword_score(
  p_side    integer,
  p_seconds integer,
  p_checks  integer,
  p_reveals integer
)
returns bigint
language sql
immutable
set search_path = ''
as $$
  select greatest(0,
    greatest(
      case when p_side = 7 then 200 else 100 end,
      (case when p_side = 7 then 2000 else 1000 end)
        - 4 * greatest(0, p_seconds - case when p_side = 7 then 60 else 30 end)
    ) - 50 * p_checks - 100 * p_reveals
  )::bigint
$$;

comment on function public.crossword_rules_version() is
  'The crossword rules version the database can verify. A rules change needs a new version and a new verifier.';
comment on function public.crossword_max_actions() is
  'The most moves a crossword submission may carry. A request bound, not a puzzle length.';
comment on function public.crossword_score(integer, integer, integer, integer) is
  'A solved crossword''s score: 1000 (mini) or 2000 (midi) for a grace period of 30 or 60 s, then 4 points a second off to a tenth of that; less 50 a check and 100 a revealed letter; never below zero.';

