-- A day's grid. Day 0 was a Thursday, so day d falls on weekday (d + 4) mod 7,
-- 0 a Sunday and 6 a Saturday. Weekdays take the minis in turn and weekends the
-- midis: the k-th weekday since day 0 is mini k mod the bank's size.
create or replace function public.crossword_grid(p_day bigint)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_weeks    bigint;
  v_rest     integer;
  v_weekends bigint;
  v_index    integer;
  v_weekday  integer;
begin
  if p_day is null or p_day < 0 then
    raise exception 'a crossword day is zero or more' using errcode = '22023';
  end if;
  v_weeks := p_day / 7;
  v_rest := (p_day % 7)::integer;
  v_weekends := v_weeks * 2;
  for v_index in 0..v_rest - 1 loop
    if (4 + v_index) % 7 in (0, 6) then
      v_weekends := v_weekends + 1;
    end if;
  end loop;
  v_weekday := ((p_day + 4) % 7)::integer;
  if v_weekday in (0, 6) then
    return (public.crossword_midis())[(v_weekends % array_length(public.crossword_midis(), 1))::integer + 1];
  end if;
  return (public.crossword_minis())[((p_day - v_weekends) % array_length(public.crossword_minis(), 1))::integer + 1];
end;
$$;

