-- The daily crossword: the thirteenth runtime.
--
-- One crossword a day, the same for everyone: a 5×5 mini on weekdays and a 7×7
-- midi at weekends, from a bank of original puzzles. Faster solves score more;
-- checking or revealing letters costs points. What this migration changes, and
-- why:
--
--   1. The rules, as constants the database owns: `crossword@1`, a 2048-move
--      submission bound, and the scoring — a base for solving (1000 for a mini,
--      2000 for a midi) that holds for a grace period and then falls four points a
--      second to a floor, less 50 a check and 100 a revealed letter.
--
--   2. The bank, `crossword_minis()` and `crossword_midis()`: the solution grids
--      only, generated by scripts/generate-crossword-bank.mjs. The clues are the
--      client's; the database never shows a puzzle, it verifies a solve.
--
--   3. The day: `crossword_day()` is the UTC day number, which is the session's
--      seed, and `crossword_grid(day)` picks that day's puzzle — weekdays walk the
--      minis in order, weekends the midis.
--
--   4. `public.complete_crossword_run`, the verifier. It replays every move —
--      letters, checks and reveals — on the day's grid. A run scores only if it
--      solves the grid, and the score is the database's own: it times the solve
--      from the session's start by its own clock, so the client's number is an
--      estimate the verifier does not need to match. One ranked completion a day,
--      as 7 Second: a second completion of the same day is `already_played`.
--
--   5. `public.start_game_session` learns (`crossword`, `crossword@1`), deals the
--      day's seed, and answers `already_played` to a signed-in player who has
--      finished today's.
--
-- Nothing here puts the crossword in the catalogue:
-- `20261116120100_crossword_playable.sql` does, after the deployment carrying the
-- runtime is live. See docs/games/README.md.

