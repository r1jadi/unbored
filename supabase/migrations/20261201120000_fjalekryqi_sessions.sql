-- A day's Albanian grid, walked as crossword_grid walks the English bank.
create or replace function public.fjalekryqi_grid(p_day bigint)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_weeks    bigint;
  v_rest     integer;
  v_weekends bigint;
  v_index    integer;
  v_weekday  integer;
begin
  if p_day is null or p_day < 0 then
    raise exception 'a crossword day is zero or more' using errcode = '22023';
  end if;
  v_weeks := p_day / 7;
  v_rest := (p_day % 7)::integer;
  v_weekends := v_weeks * 2;
  for v_index in 0..v_rest - 1 loop
    if (4 + v_index) % 7 in (0, 6) then
      v_weekends := v_weekends + 1;
    end if;
  end loop;
  v_weekday := ((p_day + 4) % 7)::integer;
  if v_weekday in (0, 6) then
    return (public.fjalekryqi_midis())[(v_weekends % array_length(public.fjalekryqi_midis(), 1))::integer + 1];
  end if;
  return (public.fjalekryqi_minis())[((p_day - v_weekends) % array_length(public.fjalekryqi_minis(), 1))::integer + 1];
end;
$$;

comment on function public.fjalekryqi_grid(bigint) is
  'The Fjalekryqi grid for a UTC day: a 7×7 midi on Saturday and Sunday, a 5×5 mini otherwise. Mirrored by src/lib/games/crossword.ts.';

revoke all on function public.fjalekryqi_grid(bigint) from public;

