-- Fjalekryqi (`fjalekryqi@1`): the daily crossword in Albanian.
--
-- It is the crossword game itself, not a new catalogue entry: a player whose app
-- is in Albanian starts the crossword's session under `fjalekryqi@1` and gets
-- the day's Albanian puzzle. Everything but the puzzle and its alphabet is the
-- crossword's — the day as the seed, the moves, the scoring
-- (`crossword_score`), the 2048-move bound and one ranked solve a day, which
-- holds across both languages because it is one game. The board is the game's
-- board, so English and Albanian solves rank together.
--
--   1. The rules version and the bank, `fjalekryqi_minis()` and
--      `fjalekryqi_midis()`: solution grids only, generated by
--      `scripts/generate-crossword-bank.mjs --lang sq`. The alphabet is
--      Albanian's single letters: A–Z (code 1–26), Ç (27) and Ë (28); a digraph
--      such as SH takes two squares.
--   2. `fjalekryqi_grid(day)`: weekdays walk the minis and weekends the midis,
--      as `crossword_grid` does.
--   3. `public.complete_fjalekryqi_run`, the verifier: the crossword's replay
--      over this bank and alphabet.
--   4. `public.start_game_session` accepts (`crossword`, `fjalekryqi@1`).

-- ─────────────────────────────────────────────────────────────────────────────
-- The rules and the bank
-- ─────────────────────────────────────────────────────────────────────────────

