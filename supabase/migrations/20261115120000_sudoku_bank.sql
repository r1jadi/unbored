-- Sudoku, rules sudoku@2: boards with one solution, and a gentler start.
--
-- sudoku@1 dealt random givens on a random grid, so a board could have more than
-- one solution, and difficulty came only from how many cells started filled.
-- sudoku@2 deals every board from a bank of puzzles that each have exactly one
-- solution, graded by the hardest technique a logical solver needs, and the
-- level picks the grade. What this migration changes, and why:
--
--   1. The bank, `sudoku_bank()`: 200 puzzles in four tiers of 50 — gentle (only
--      the last place for a digit in a box, 36 givens), easy (singles in any
--      row, column or box), medium (pair and line eliminations) and hard (several
--      of them, 23 to 27 givens). Generated by scripts/generate-sudoku-bank.mjs,
--      which src/lib/games/sudoku-bank.ts copies exactly.
--
--   2. `sudoku_start(seed, level)`: the board's starting cells. The level picks
--      the tier (`sudoku_tier`: boards 1–2 gentle, 3–5 easy, 6–9 medium, then
--      hard) and the seed picks a puzzle in it, then disguises it with the same
--      shuffles sudoku@1 used to draw a grid — the digits relabelled, the rows
--      and columns shuffled within bands and stacks, the bands and stacks
--      shuffled. None of those changes how many solutions a puzzle has, so a
--      bank puzzle stays unique, and no search runs in the database.
--
--   3. The clock follows the tiers: six minutes to start, and every solved board
--      adds the next board's allowance (`sudoku_allowance_ms`: four minutes for
--      gentle, five for easy, eight for medium, ten for hard).
--
--   4. `complete_sudoku_run` replays sudoku@2 runs on these boards, and still
--      replays sudoku@1 runs exactly as before, so a session opened before this
--      migration finishes under the rules it was issued with. A board is solved,
--      as before, when it is full and obeys the rules.
--
--   5. `start_game_session` issues sudoku@2, and still accepts sudoku@1.
--
-- Apply before the client that sends sudoku@2. See docs/games/README.md.

-- ─────────────────────────────────────────────────────────────────────────────
-- The rules version new runs pin
-- ─────────────────────────────────────────────────────────────────────────────

create or replace function public.sudoku_rules_version()
returns text language sql immutable set search_path = '' as $$ select 'sudoku@2'::text $$;

