-- The tier a level's board is drawn from: 0 gentle, 1 easy, 2 medium, 3 hard.
create or replace function public.sudoku_tier(p_level integer)
returns integer
language plpgsql
immutable
set search_path = ''
as $$
begin
  if p_level is null or p_level < 1 then
    raise exception 'a Sudoku level is one or more' using errcode = '22023';
  end if;
  return case when p_level <= 2 then 0 when p_level <= 5 then 1 when p_level <= 9 then 2 else 3 end;
end;
$$;

-- The time a board of a tier is given.
create or replace function public.sudoku_allowance_ms(p_tier integer)
returns bigint language sql immutable set search_path = '' as $$
  select case p_tier when 0 then 240000 when 1 then 300000 when 2 then 480000 else 600000 end::bigint
$$;

-- The clock a sudoku@2 run has earned with `p_cleared` boards solved: six
-- minutes, plus, for every solved board, the allowance of the board after it.
create or replace function public.sudoku_tiered_budget_ms(p_cleared integer)
returns bigint
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_total bigint := 360000;
  v_level integer;
begin
  for v_level in 1..greatest(coalesce(p_cleared, 0), 0) loop
    v_total := v_total + public.sudoku_allowance_ms(public.sudoku_tier(v_level + 1));
  end loop;
  return v_total;
end;
$$;

